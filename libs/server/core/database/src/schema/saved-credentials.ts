import { sql } from 'drizzle-orm';
import { integer, sqliteTable, text, uniqueIndex } from 'drizzle-orm/sqlite-core';
import { users } from './users';

/** Provider tokens arrive with pull requests. */
export const CREDENTIAL_KINDS = [ 'https', 'ssh-key' ] as const;
export type CredentialKind = (typeof CREDENTIAL_KINDS)[number];

/**
 * Credentials saved in a user's profile (AR-17, A-4.4). `secret` is encrypted
 * with the binding `{ table: 'saved_credentials', recordId: id, userId }`
 * (NF-8.3); `null` means it was deleted by an encryption key reset (NF-8.6).
 */
export const savedCredentials = sqliteTable(
  'saved_credentials',
  {
    id: integer('id').primaryKey({ autoIncrement: true }),
    userId: integer('user_id').notNull().references(() => users.id, { onDelete: 'cascade' }),
    kind: text('kind', { enum: CREDENTIAL_KINDS }).notNull(),
    /** Unique among the user's credentials of the same kind, ignoring case (AR-18). */
    name: text('name').notNull(),
    /** HTTPS only. */
    username: text('username'),
    /** The password or token, or the private key as pasted (AR-28). */
    secret: text('secret'),
    /** SSH keys only: the public parts worked out by the backend (AR-24, AR-28). */
    sshKeyType: text('ssh_key_type'),
    sshPublicKey: text('ssh_public_key'),
    sshFingerprint: text('ssh_fingerprint'),
    sshPassphraseProtected: integer('ssh_passphrase_protected', { mode: 'boolean' }),
    /** Generated by Front Burner (AR-29). */
    sshGenerated: integer('ssh_generated', { mode: 'boolean' }),
    createdAt: integer('created_at', { mode: 'timestamp_ms' }).notNull()
  },
  table => [
    uniqueIndex('saved_credentials_user_kind_name_unique').on(table.userId, table.kind, sql`lower(${table.name})`)
  ]
);

export type SavedCredential = typeof savedCredentials.$inferSelect;
export type NewSavedCredential = typeof savedCredentials.$inferInsert;
